    const translationRules = Object.keys(translations)
        .sort((a, b) => b.length - a.length)
        .map((source) => ({
            source,
            replacement: translations[source]
        }));
    const isWordCharacter = (character) => Boolean(character && /[\p{L}\p{N}_]/u.test(character));

    const translateRelativeTime = (text) => text.replace(
        /\bhace\s+(\d+)\s+(segundos?|s|minutos?|mins?|m|horas?|h|días?|d|semanas?|sem|meses?|años?|a)\b/giu,
        (_match, amount, rawUnit) => {
            const unit = rawUnit.toLocaleLowerCase('es');
            const unitName = unit.startsWith('sem') ? 'week'
                : unit.startsWith('s') ? 'second'
                : (unit.startsWith('min') || unit === 'm') ? 'minute'
                    : (unit.startsWith('h')) ? 'hour'
                        : (unit.startsWith('d')) ? 'day'
                            : unit.startsWith('mes') ? 'month' : 'year';
            return `${amount} ${unitName}${amount === '1' ? '' : 's'} ago`;
        }
    );

    const translateText = (text) => {
        if (!text || text.trim() === '') return text;
        let translated = translateRelativeTime(text);
        translationRules.forEach(({ source, replacement }) => {
            const normalizedSource = source.toLocaleLowerCase('es');
            const escapedSource = normalizedSource.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
            const standaloneLabel = new RegExp(`^[\\s\\p{P}\\p{S}]*${escapedSource}[\\s\\p{P}\\p{S}]*$`, 'u');
            const isStandalone = standaloneLabel.test(translated.trim().toLocaleLowerCase('es'));
            const wordCount = source.trim().split(/\s+/u).length;
            if (!isStandalone && (wordCount < 3 || source.trim().length < 20)) return;
            let normalizedText = translated.toLocaleLowerCase('es');
            let index = normalizedText.indexOf(normalizedSource);
            while (index !== -1) {
                const before = translated[index - 1];
                const after = translated[index + source.length];
                if (!isWordCharacter(before) && !isWordCharacter(after)) {
                    translated = translated.slice(0, index) + replacement + translated.slice(index + source.length);
                    normalizedText = translated.toLocaleLowerCase('es');
                    index = normalizedText.indexOf(normalizedSource, index + replacement.length);
                } else {
                    index = normalizedText.indexOf(normalizedSource, index + source.length);
                }
            }
        });
        return translated;
    };

    const applyTranslations = () => {
        if (getLanguage() !== 'en') {
            document.documentElement.lang = 'es';
            return;
        }
        document.documentElement.lang = 'en';

        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        const nodes = [];
        let node;
        while ((node = walker.nextNode())) {
            if (node.parentElement && ['SCRIPT', 'STYLE', 'TEXTAREA'].includes(node.parentElement.tagName)) continue;
            nodes.push(node);
        }
        nodes.forEach((textNode) => {
            const translated = translateText(textNode.nodeValue);
            if (translated !== textNode.nodeValue) textNode.nodeValue = translated;
        });

        document.querySelectorAll('[placeholder],[title],[aria-label],[data-tip],[alt]').forEach((element) => {
            ['placeholder', 'title', 'aria-label', 'data-tip', 'alt'].forEach((attribute) => {
                if (element.hasAttribute(attribute)) {
                    const current = element.getAttribute(attribute);
                    const translated = translateText(current);
                    if (translated !== current) element.setAttribute(attribute, translated);
                }
            });
        });

        document.querySelectorAll('input[readonly], input:disabled').forEach((input) => {
            const translated = translateText(input.value);
            if (translated !== input.value) input.value = translated;
        });
    };

    const createGlobalSwitcher = () => {
        if (document.querySelector('.language-switcher')) return;
        const form = document.createElement('form');
        form.className = 'language-switcher global-language-switcher';
        form.method = 'post';
        form.action = '/i18n/setlang/';
        form.innerHTML =
            '<input type="hidden" name="next">' +
            '<button class="language-switcher-button' + (getLanguage() === 'es' ? ' is-active' : '') + '" type="submit" name="language" value="es">ES</button>' +
            '<span class="language-switcher-separator" aria-hidden="true">|</span>' +
            '<button class="language-switcher-button' + (getLanguage() === 'en' ? ' is-active' : '') + '" type="submit" name="language" value="en">EN</button>';
        form.querySelector('input[name="next"]').value = window.location.pathname + window.location.search;
        const csrfInput = document.querySelector('[name="csrfmiddlewaretoken"]');
        const csrfMeta = document.querySelector('meta[name="csrf-token"]');
        const csrfCookie = document.cookie.match(/(?:^|; )csrftoken=([^;]*)/);
        const csrfToken = csrfInput?.value || csrfMeta?.content || (csrfCookie ? decodeURIComponent(csrfCookie[1]) : '');
        if (csrfToken) {
            const input = document.createElement('input');
            input.type = 'hidden';
            input.name = 'csrfmiddlewaretoken';
            input.value = csrfToken;
            form.prepend(input);
        }
        document.body.appendChild(form);
    };

    const start = () => {
        applyTranslations();
        createGlobalSwitcher();
        restorePostScroll();
    };

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', start);
    } else {
        start();
    }

